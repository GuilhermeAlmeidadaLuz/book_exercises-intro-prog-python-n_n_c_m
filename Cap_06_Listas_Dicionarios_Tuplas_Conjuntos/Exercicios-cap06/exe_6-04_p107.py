# O que acontece quando não verificamos se a lista está vazia antes de chamarmos o método pop?

# Resposta:
# Como a lista está vazia, o índice 0 que comporta o 1º elemento da lista não existe, então,
# ao chamar o método pop, uma mensagem de erro capturado aparece informando que houve uma tentativa de
# retirada de um elemento de uma lista vazia. Portanto, não é possível executar o método, visto que o índice
# não pertencente ao intervalo de índices da lista, sendo um índice inexistente.
